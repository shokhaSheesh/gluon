import { useRef, useState } from 'react';
import clsx from 'clsx';
import { Eye, EyeOff, ImageUp, Wand2, X } from 'lucide-react';
import { Field, Input } from '../../components/ui';
import { slug, type CatalogService } from '../../lib/merchant';
import { genPassword } from './merchant/Team';
import './merchant/merchant.css';

const COLORS = ['#1677FF', '#22A35B', '#6D5DF6', '#F26B1D', '#7A3FF2', '#0891B2', '#DC2626', '#CA8A04'];
const digits = (v: string) => Number(v.replace(/\D/g, '') || 0);

/** Logo upload (PNG / SVG / JPG up to 300 KB) with preview. */
export function LogoUpload({ value, onChange, wide }: { value?: string; onChange: (v?: string) => void; wide?: boolean }) {
  const file = useRef<HTMLInputElement>(null);
  const [err, setErr] = useState('');
  return (
    <div className="lu">
      <button type="button" className={clsx('lu-box', wide && 'wide')} onClick={() => file.current?.click()}>
        {value ? <img src={value} alt="" /> : <span className="col gap-4" style={{ alignItems: 'center' }}><ImageUp size={20} /><span className="t-xs">Загрузить</span></span>}
      </button>
      <div className="col gap-4">
        <span className="t-xs muted">PNG, SVG или JPG до 300 КБ</span>
        {value && <button type="button" className="btn-link t-xs row gap-4" onClick={() => onChange(undefined)}><X size={12} /> Удалить</button>}
        {err && <span className="t-xs" style={{ color: 'var(--error)' }}>{err}</span>}
      </div>
      <input ref={file} type="file" hidden accept="image/png,image/svg+xml,image/jpeg" onChange={(e) => {
        const f = e.target.files?.[0];
        e.target.value = '';
        if (!f) return;
        if (f.size > 300_000) { setErr('Файл больше 300 КБ'); return; }
        const r = new FileReader();
        r.onload = () => { setErr(''); onChange(String(r.result)); };
        r.readAsDataURL(f);
      }} />
    </div>
  );
}

/** Login + password of a partner cabinet (generated by default). */
export function CabinetFields({ login, setLogin, pw, setPw, placeholder, err }: { login: string; setLogin: (v: string) => void; pw: string; setPw: (v: string) => void; placeholder: string; err?: string }) {
  const [show, setShow] = useState(true);
  return (
    <div className="bc-access">
      <b className="t-sm">Кабинет партнёра</b>
      <Field label="Логин" error={err}><Input value={login} onChange={(e) => setLogin(e.target.value.trim().toLowerCase())} placeholder={placeholder} error={!!err} autoComplete="off" /></Field>
      <Field label="Пароль">
        <div className="row gap-8">
          <Input className="grow" type={show ? 'text' : 'password'} value={pw} onChange={(e) => setPw(e.target.value)} autoComplete="new-password"
            right={<button type="button" className="tm-eye" onClick={() => setShow((v) => !v)} aria-label="show">{show ? <EyeOff size={16} /> : <Eye size={16} />}</button>} />
          <button type="button" className="btn btn-secondary" onClick={() => { setPw(genPassword()); setShow(true); }}><Wand2 size={16} /> Сгенерировать</button>
        </div>
      </Field>
    </div>
  );
}

export interface ServiceDraft { svc: CatalogService; price: number; mode?: 'all' | 'new'; login?: string; password?: string }

/**
 * Create or edit a service. Creating also opens its partner cabinet (login + password).
 * Editing the price asks how to apply it: for everyone from their next payment, or only for new clients.
 */
export function ServiceForm({ initial, price: price0, takenIds, takenLogins, onClose, onSave }: {
  initial?: CatalogService; price?: number; takenIds: string[]; takenLogins: string[]; onClose: () => void; onSave: (d: ServiceDraft) => void;
}) {
  const editing = !!initial;
  const [f, setF] = useState<CatalogService>(initial ?? { id: '', name: '', type: '', description: '', color: COLORS[takenIds.length % COLORS.length] });
  const [price, setPrice] = useState(String(price0 ?? ''));
  const [mode, setMode] = useState<'all' | 'new'>('all');
  const [login, setLogin] = useState('');
  const [pw, setPw] = useState(genPassword);
  const [err, setErr] = useState<Record<string, string>>({});
  const priceChanged = editing && digits(price) !== price0;

  const submit = () => {
    const e: Record<string, string> = {};
    const id = editing ? f.id : slug(f.name);
    if (f.name.trim().length < 2) e.name = 'Введите название';
    else if (!editing && takenIds.includes(id)) e.name = 'Такой сервис уже есть';
    if (!f.type.trim()) e.type = 'Укажите категорию';
    if (f.description.trim().length < 10) e.description = 'Опишите сервис в одном-двух предложениях';
    if (digits(price) <= 0) e.price = 'Укажите цену';
    const l = login || id;
    if (!editing && !/^[a-z0-9._-]{3,}$/.test(l)) e.login = 'Минимум 3 символа: латиница, цифры, . _ -';
    else if (!editing && takenLogins.includes(l)) e.login = 'Такой логин уже есть';
    setErr(e);
    if (Object.keys(e).length) return;
    onSave({ svc: { ...f, id, name: f.name.trim(), type: f.type.trim(), description: f.description.trim() }, price: digits(price), mode: priceChanged ? mode : undefined, login: editing ? undefined : l, password: editing ? undefined : pw });
  };

  return (
    <div className="col gap-16" style={{ padding: 24 }}>
      <div className="row gap-16" style={{ alignItems: 'flex-start' }}>
        <LogoUpload value={f.logo} onChange={(logo) => setF({ ...f, logo })} />
        <div className="col gap-12 grow">
          <Field label="Название" error={err.name}><Input value={f.name} onChange={(e) => setF({ ...f, name: e.target.value })} placeholder="Например: Moy Sklad" error={!!err.name} disabled={editing} /></Field>
          <Field label="Категория" error={err.type}><Input value={f.type} onChange={(e) => setF({ ...f, type: e.target.value })} placeholder="Например: Складской учёт" error={!!err.type} /></Field>
        </div>
      </div>
      <Field label="Описание для магазина" error={err.description}>
        <textarea className="cb-note" rows={2} value={f.description} onChange={(e) => setF({ ...f, description: e.target.value })} maxLength={140} placeholder="Что даёт сервис бизнесу" />
      </Field>
      <Field label="Цена подписки в месяц" error={err.price}>
        <Input value={digits(price) ? digits(price).toLocaleString('ru-RU') : ''} onChange={(e) => setPrice(e.target.value)} suffixBox="сум" inputMode="numeric" placeholder="0" error={!!err.price} />
      </Field>
      {priceChanged && (
        <div className="pf-apply">
          <b className="t-sm">Как применить новую цену</b>
          <label className="checkbox t-sm"><input type="radio" checked={mode === 'all'} onChange={() => setMode('all')} /> Для всех клиентов — со следующей оплаты</label>
          <label className="checkbox t-sm"><input type="radio" checked={mode === 'new'} onChange={() => setMode('new')} /> Только для новых клиентов</label>
        </div>
      )}
      {!editing && <CabinetFields login={login} setLogin={setLogin} pw={pw} setPw={setPw} placeholder={slug(f.name || 'service')} err={err.login} />}
      <div className="row gap-12">
        <button className="btn btn-secondary grow" onClick={onClose}>Отмена</button>
        <button className="btn btn-primary grow" onClick={submit}>{editing ? 'Сохранить' : 'Создать сервис'}</button>
      </div>
    </div>
  );
}

export interface BankDraft { id: string; name: string; logo?: string; subdomain: string; login: string; password: string }

/** New bank partner: name, logo, domain and cabinet access. */
export function BankForm({ takenIds, takenLogins, onClose, onSave }: { takenIds: string[]; takenLogins: string[]; onClose: () => void; onSave: (d: BankDraft) => void }) {
  const [name, setName] = useState('');
  const [logo, setLogo] = useState<string>();
  const [sub, setSub] = useState('');
  const [login, setLogin] = useState('');
  const [pw, setPw] = useState(genPassword);
  const [err, setErr] = useState<Record<string, string>>({});
  const id = name.trim() ? slug(name) : '';
  const domain = sub || id;

  const submit = () => {
    const e: Record<string, string> = {};
    if (name.trim().length < 3 || !id) e.name = 'Введите название банка';
    else if (takenIds.includes(id)) e.name = 'Этот банк уже подключён';
    if (!/^[a-z0-9-]{2,}$/.test(domain)) e.sub = 'Латиница, цифры и дефис';
    const l = login || id;
    if (!/^[a-z0-9._-]{3,}$/.test(l)) e.login = 'Минимум 3 символа: латиница, цифры, . _ -';
    else if (takenLogins.includes(l)) e.login = 'Такой логин уже есть';
    setErr(e);
    if (!Object.keys(e).length) onSave({ id, name: name.trim(), logo, subdomain: `${domain}.gluon.uz`, login: l, password: pw });
  };

  return (
    <div className="col gap-16" style={{ padding: 24 }}>
      <Field label="Название банка" error={err.name}><Input value={name} onChange={(e) => setName(e.target.value)} placeholder="Например: Aloqabank" error={!!err.name} /></Field>
      <Field label="Логотип"><LogoUpload value={logo} onChange={setLogo} wide /></Field>
      <Field label="Домен для клиентов банка" error={err.sub}>
        <Input value={sub} onChange={(e) => setSub(e.target.value.trim().toLowerCase())} placeholder={id || 'bank'} suffixBox=".gluon.uz" error={!!err.sub} />
      </Field>
      <CabinetFields login={login} setLogin={setLogin} pw={pw} setPw={setPw} placeholder={id || 'bank'} err={err.login} />
      <div className="row gap-12">
        <button className="btn btn-secondary grow" onClick={onClose}>Отмена</button>
        <button className="btn btn-primary grow" onClick={submit}>Создать банк</button>
      </div>
    </div>
  );
}
